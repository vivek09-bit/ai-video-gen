    # Auto-detection priority across configured keys:
    if os.environ.get("DEEPSEEK_API_KEY"):
        return "DeepSeek", "https://api.deepseek.com/v1", os.environ.get("DEEPSEEK_API_KEY"), model_str or "deepseek-chat"

    if os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY"):
        key = os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY")
        return "Fireworks AI", "https://api.fireworks.ai/inference/v1", key, model_str or "accounts/fireworks/models/deepseek-v3"

    if os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY"):
        key = os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY")
        return "Together AI", "https://api.together.xyz/v1", key, model_str or "deepseek-ai/DeepSeek-V3"

    if os.environ.get("OMNIROUTE_API_KEY") or os.environ.get("OPENROUTER_API_KEY"):
        key = os.environ.get("OMNIROUTE_API_KEY") or os.environ.get("OPENROUTER_API_KEY")
        base = os.environ.get("OMNIROUTE_BASE_URL") or os.environ.get("OPENROUTER_BASE_URL") or "https://openrouter.ai/api/v1"
        default_omni_model = os.environ.get("OMNIROUTE_MODEL") or os.environ.get("OPENROUTER_MODEL") or os.environ.get("LLM_MODEL") or "auto"
