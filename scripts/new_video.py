        if model_str.startswith("deepseek-"):
            key = os.environ.get("DEEPSEEK_API_KEY")
            return "DeepSeek", "https://api.deepseek.com/v1", key, model_str
        if model_str.startswith("gpt-"):
            key = os.environ.get("OPENAI_API_KEY")
