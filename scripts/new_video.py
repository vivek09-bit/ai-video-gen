    cli_img_prov = args.image_provider
    if not cli_img_prov:
        if args.vast or args.vast_url or args.vast_instance is not None or needs_vast or args.visual_mode == "video":
            cli_img_prov = "vast"
        else:
            cli_img_prov = os.environ.get("IMAGE_PROVIDER") or ""
