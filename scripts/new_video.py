def normalize_llm_provider(name: str | None) -> str:
    """Normalize provider aliases to canonical names."""
    if not name:
        return ""
    n = name.lower().strip().replace("-", "").replace("_", "").replace(" ", "")
    if n in ("deepseek", "deepseekai"):
        return "deepseek"
    if n in ("firework", "fireworks", "fireworksai"):
        return "fireworks"
    if n in ("together", "togetherai"):
        return "together"
    if n in ("omniroute", "openrouter", "omni"):
        return "openrouter"
    if n in ("openai", "chatgpt"):
        return "openai"
    if n in ("ollama", "local"):
        return "ollama"
    return name.lower().strip()


def resolve_llm_writer(
    requested_model: str | None = None,
    requested_provider: str | None = None,
) -> tuple[str, str, str | None, str] | None:
    """Resolve reachable writer as (label, base_url, api_key, model_name)."""
    req_prov = normalize_llm_provider(requested_provider)
    model_str = (requested_model or "").strip()

    # If --model was passed as a provider shortcut (e.g. --model deepseek, --model omniroute, --model together)
    if not req_prov and model_str:
        norm = normalize_llm_provider(model_str)
        if norm in ("deepseek", "fireworks", "together", "openrouter", "openai", "ollama"):
            req_prov = norm
            model_str = ""  # use provider default

    # If provider is explicitly specified or inferred from shortcut
    if req_prov == "deepseek":
        key = os.environ.get("DEEPSEEK_API_KEY")
        if not key:
            print("  error: DeepSeek requested, but DEEPSEEK_API_KEY is not set.", file=sys.stderr)
            return None
        return "DeepSeek", "https://api.deepseek.com/v1", key, model_str or "deepseek-chat"

    if req_prov == "fireworks":
        key = os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY")
        if not key:
            print("  error: Fireworks AI requested, but FIREWORKS_API_KEY is not set.", file=sys.stderr)
            return None
        return "Fireworks AI", "https://api.fireworks.ai/inference/v1", key, model_str or "accounts/fireworks/models/deepseek-v3"

    if req_prov == "together":
        key = os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY")
        if not key:
            print("  error: Together AI requested, but TOGETHER_API_KEY is not set.", file=sys.stderr)
            return None
