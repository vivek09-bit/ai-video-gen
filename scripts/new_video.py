def caption_options(
    style: str,
    enabled: bool = True,
    format_profile: beats.VideoFormat | None = None,
    hinglish: bool = False,
    bottom_margin: float | None = None,
) -> dict:
    """On-screen text settings.

    `statement` shows a few words in the middle of frame.
    `subtitle` is the conventional readable band at the bottom (default).
    Scales font size and safe bottom margin adaptively to video format (e.g. reels).
    """
    scale = format_profile.caption_scale if format_profile else 1.0
    if bottom_margin is not None:
        bot_margin = float(bottom_margin)
    else:
        bot_margin = format_profile.bottom_margin if format_profile else 0.14

    if style == "statement":
        return {
            "enabled": enabled,
            "wordsPerCue": 3,
            "bottom": bot_margin,
            "fontSize": int(round(68 * scale)),
            "uppercase": False,
            "highlight": True,
            "position": "center",
            "outline": 0,
            "panel": False,
            "maxWidth": 0.82,
            "rise": 20,
            "hinglish": hinglish,
        }
    return {
        "enabled": enabled,
        "wordsPerCue": 5,
        "bottom": bot_margin,
        "fontSize": int(round(48 * scale)),
        "uppercase": False,
        "highlight": True,
        "position": "bottom",
        "outline": 0,
        "panel": True,
        "maxWidth": 0.88 if (format_profile and format_profile.height > format_profile.width) else 0.92,
        "rise": 14,
        "hinglish": hinglish,
    }


def build_script(
    planned: dict,
    title: str,
    blocks: list[tuple],
    *,
    voice: str,
    speed: float,
    captions: dict,
    genre_profile: beats.GenreProfile | None = None,
    visual_style: str | None = None,
    secondary_voice: str | None = None,
    show_headline: bool = False,
) -> tuple[dict, list[int]]:
    """Combine the planned structure with written narration into script.json."""
    gp = genre_profile or beats.get_genre(planned.get("genre"))
    scenes = []
    missing: list[int] = []

    for index, scene in enumerate(planned["scenes"]):
        headline, visual_keywords, narration = ("", "", "")
        if index < len(blocks):
            item = blocks[index]
            if len(item) >= 3:
                headline, visual_keywords, narration = item[0], item[1], item[2]
            elif len(item) == 2:
                headline, narration = item[0], item[1]
                if " | VISUAL:" in headline or " | visual:" in headline.lower():
                    parts = re.split(r"\s*\|\s*visual:\s*", headline, flags=re.IGNORECASE, maxsplit=1)
                    headline = parts[0].strip()
                    visual_keywords = parts[1].strip() if len(parts) > 1 else ""

        if not narration.strip():
            missing.append(index + 1)
            # A silent scene still renders as a held shot, so the video stays
            # watchable instead of crashing partway through.
            narration = ""

        # Pass the planned scene through wholesale and override only what the
        # writer supplies. Listing keys by hand silently drops anything new the
        # planner starts emitting -- which is exactly how the acting block was
        # lost on the first pass.
        entry = {key: value for key, value in scene.items() if not key.startswith("_")}
        resolved_headline = headline or scene["headline"]
        entry["headline"] = resolved_headline if show_headline else ""
        if visual_keywords:
            entry["visualKeywords"] = visual_keywords
        elif resolved_headline and not show_headline:
            # Preserve the generated headline as visual keywords for image retrieval if needed
            entry["visualKeywords"] = resolved_headline
        entry["lines"] = [{"character": None, "text": narration}] if narration else []
        scenes.append(entry)

    width = planned.get("width", 1920)
    height = planned.get("height", 1080)
    fps = planned.get("fps", 30)
    aspect_ratio = planned.get("aspectRatio", "16:9")
    format_key = planned.get("format", "landscape")

    characters = dict(planned.get("characters", {}))
    if "lead" in characters:
        characters["lead"] = dict(characters["lead"])
        characters["lead"]["voice"] = voice
    if secondary_voice and "side" in characters:
        characters["side"] = dict(characters["side"])
        characters["side"]["voice"] = secondary_voice

    script = {
        "title": title or planned["topic"],
        "topic": planned["topic"],
        "language": planned.get("language", "hi"),
        "genre": planned.get("genre", gp.key),
        "visualStyle": visual_style,
        "format": format_key,
        "aspectRatio": aspect_ratio,
        "width": width,
        "height": height,
        "fps": fps,
        "voice": voice,
        "secondaryVoice": secondary_voice,
        "speed": speed,
        "sentencePauseSeconds": 0.12,
        "ambience": planned.get("ambience"),
        "captions": captions,
        "theme": planned.get("theme") or gp.theme,
        "characters": characters,
        "scenes": scenes,
    }
    return script, missing


def run_step(label: str, command: list[str], *, shell: bool = False) -> bool:
    print(f"\n--- {label} ---")
    result = subprocess.run(command, shell=shell, cwd=str(ROOT))
    if result.returncode != 0:
        print(f"{label} failed with exit code {result.returncode}", file=sys.stderr)
        return False
    return True


def report(args, target_sec: float | None = None) -> None:
    """Summarise the run: how long the narration actually came out."""
    print()
    print("=" * 74)
    print("DONE")
    print("=" * 74)
    if not GENERATED.exists():
        return
    timing = json.loads(GENERATED.read_text(encoding="utf-8"))["timings"]
    actual = timing["totalDuration"]
    target_seconds = target_sec if target_sec is not None else (args.seconds if getattr(args, "seconds", None) else args.minutes * 60)
    delta = actual - target_seconds
    print(f"  target : {target_seconds / 60:.2f} min ({target_seconds:.0f}s)")
    print(f"  actual : {actual / 60:.2f} min ({actual:.0f}s)")
    print(f"  delta  : {delta:+.0f}s  ({delta / target_seconds * 100:+.1f}%)")
    if not args.no_render:
        print(f"  output : {args.out}")


