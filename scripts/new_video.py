def normalize_llm_provider(name: str | None) -> str:
    """Normalize provider aliases to canonical names."""
    if not name:
        return ""
    n = name.lower().strip().replace("-", "").replace("_", "").replace(" ", "")
    if n in ("deepseek", "deepseekai"):
        return "deepseek"
    if n in ("firework", "fireworks", "fireworksai"):
        return "fireworks"
    if n in ("together", "togetherai"):
        return "together"
    if n in ("omniroute", "openrouter", "omni"):
        return "openrouter"
    if n in ("openai", "chatgpt"):
        return "openai"
    if n in ("ollama", "local"):
        return "ollama"
    return name.lower().strip()


def resolve_llm_writer(
    requested_model: str | None = None,
    requested_provider: str | None = None,
) -> tuple[str, str, str | None, str] | None:
    """Resolve reachable writer as (label, base_url, api_key, model_name)."""
    req_prov = normalize_llm_provider(requested_provider)
    model_str = (requested_model or "").strip()

    # If --model was passed as a provider shortcut (e.g. --model deepseek, --model omniroute, --model together)
    if not req_prov and model_str:
        norm = normalize_llm_provider(model_str)
        if norm in ("deepseek", "fireworks", "together", "openrouter", "openai", "ollama"):
            req_prov = norm
            model_str = ""  # use provider default

    # If provider is explicitly specified or inferred from shortcut
    if req_prov == "deepseek":
        key = os.environ.get("DEEPSEEK_API_KEY")
        if not key:
            print("  error: DeepSeek requested, but DEEPSEEK_API_KEY is not set.", file=sys.stderr)
            return None
        return "DeepSeek", "https://api.deepseek.com/v1", key, model_str or "deepseek-chat"

    if req_prov == "fireworks":
        key = os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY")
        if not key:
            print("  error: Fireworks AI requested, but FIREWORKS_API_KEY is not set.", file=sys.stderr)
            return None
        return "Fireworks AI", "https://api.fireworks.ai/inference/v1", key, model_str or "accounts/fireworks/models/deepseek-v3"

    if req_prov == "together":
        key = os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY")
        if not key:
            print("  error: Together AI requested, but TOGETHER_API_KEY is not set.", file=sys.stderr)
            return None
        return "Together AI", "https://api.together.xyz/v1", key, model_str or "deepseek-ai/DeepSeek-V3"

    if req_prov == "openrouter":
        key = os.environ.get("OMNIROUTE_API_KEY") or os.environ.get("OPENROUTER_API_KEY")
        base = os.environ.get("OMNIROUTE_BASE_URL") or os.environ.get("OPENROUTER_BASE_URL") or "https://openrouter.ai/api/v1"
        base = base.strip().rstrip("/")
        if base.startswith("http://http://"):
            base = base.replace("http://http://", "http://", 1)
        elif base.startswith("https://https://"):
            base = base.replace("https://https://", "https://", 1)
        if not key:
            print("  error: Omniroute/OpenRouter requested, but OMNIROUTE_API_KEY or OPENROUTER_API_KEY is not set.", file=sys.stderr)
            return None
        default_omni_model = os.environ.get("OMNIROUTE_MODEL") or os.environ.get("OPENROUTER_MODEL") or os.environ.get("LLM_MODEL") or "auto"
        return "Omniroute / OpenRouter", base, key, model_str or default_omni_model

    if req_prov == "openai":
        key = os.environ.get("OPENAI_API_KEY")
        if not key:
            print("  error: OpenAI requested, but OPENAI_API_KEY is not set.", file=sys.stderr)
            return None
        return "OpenAI", "https://api.openai.com/v1", key, model_str or "gpt-4o-mini"

    if req_prov == "ollama":
        return "Ollama (local)", OLLAMA_URL, None, model_str or "llama3.1"

    # If a specific model ID was given (e.g. accounts/fireworks/..., deepseek-ai/..., deepseek-chat, gpt-4o)
    if model_str:
        if model_str.startswith("accounts/fireworks/"):
            key = os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY")
            return "Fireworks AI", "https://api.fireworks.ai/inference/v1", key, model_str
        if model_str.startswith("deepseek-ai/") or model_str.startswith("meta-llama/"):
            key = os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY")
            return "Together AI", "https://api.together.xyz/v1", key, model_str
        if model_str.startswith("deepseek-"):
            key = os.environ.get("DEEPSEEK_API_KEY")
            return "DeepSeek", "https://api.deepseek.com/v1", key, model_str
        if model_str.startswith("gpt-"):
            key = os.environ.get("OPENAI_API_KEY")
            return "OpenAI", "https://api.openai.com/v1", key, model_str

    # Auto-detection priority across configured keys:
    if os.environ.get("DEEPSEEK_API_KEY"):
        return "DeepSeek", "https://api.deepseek.com/v1", os.environ.get("DEEPSEEK_API_KEY"), model_str or "deepseek-chat"

    if os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY"):
        key = os.environ.get("FIREWORKS_API_KEY") or os.environ.get("FIREWORK_API_KEY")
        return "Fireworks AI", "https://api.fireworks.ai/inference/v1", key, model_str or "accounts/fireworks/models/deepseek-v3"

    if os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY"):
        key = os.environ.get("TOGETHER_API_KEY") or os.environ.get("TOGETHERAI_API_KEY")
        return "Together AI", "https://api.together.xyz/v1", key, model_str or "deepseek-ai/DeepSeek-V3"

    if os.environ.get("OMNIROUTE_API_KEY") or os.environ.get("OPENROUTER_API_KEY"):
        key = os.environ.get("OMNIROUTE_API_KEY") or os.environ.get("OPENROUTER_API_KEY")
        base = os.environ.get("OMNIROUTE_BASE_URL") or os.environ.get("OPENROUTER_BASE_URL") or "https://openrouter.ai/api/v1"
        default_omni_model = os.environ.get("OMNIROUTE_MODEL") or os.environ.get("OPENROUTER_MODEL") or os.environ.get("LLM_MODEL") or "auto"
        return "Omniroute / OpenRouter", base.rstrip("/"), key, model_str or default_omni_model

    if os.environ.get("OPENAI_API_KEY"):
        return "OpenAI", "https://api.openai.com/v1", os.environ.get("OPENAI_API_KEY"), model_str or "gpt-4o-mini"

    # Custom environment variables
    base = os.environ.get("LLM_BASE_URL")
    key = os.environ.get("LLM_API_KEY")
    env_model = os.environ.get("LLM_MODEL")
    if base:
        return f"{base} (env)", base.rstrip("/"), key, model_str or env_model or "default"

    # Check local Ollama server
    try:
        req = urllib.request.Request(f"{OLLAMA_URL}/models", method="GET")
        with urllib.request.urlopen(req, timeout=2) as response:
            if response.status == 200:
                return "Ollama (local)", OLLAMA_URL, None, model_str or "llama3.1"
    except (urllib.error.URLError, OSError, ValueError):
        pass

    return None


def ask_llm(
    base_url: str,
    api_key: str | None,
    model: str,
    prompt: str,
    *,
    system_prompt: str | None = None,
) -> str:
    default_system = (
        "You write narration for engaging videos. You follow output formats exactly."
    )
    payload = json.dumps(
        {
            "model": model,
            "messages": [
                {
                    "role": "system",
                    "content": system_prompt or default_system,
                },
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.85,
        }
    ).encode("utf-8")

    headers = {
        "Content-Type": "application/json",
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) tube2dscript/1.0",
        "HTTP-Referer": "https://github.com/tube2dscript",
        "X-Title": "tube2dscript",
    }
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"

    request = urllib.request.Request(
        f"{base_url}/chat/completions", data=payload, headers=headers, method="POST"
    )
    try:
        with urllib.request.urlopen(request, timeout=300) as response:
            body = json.loads(response.read().decode("utf-8"))
        return body["choices"][0]["message"]["content"]
    except urllib.error.HTTPError as err:
        err_msg = err.read().decode("utf-8", errors="ignore")
        raise RuntimeError(f"HTTP {err.code} {err.reason} from {base_url}: {err_msg}") from err


def parse_written(text: str, scene_count: int = 999) -> tuple[str, list[tuple[str, str, str]]]:
    """Parse `TITLE:` plus `###N|headline | VISUAL: visual_tags` blocks into (title, [(headline, visual_keywords, body)])."""
    title = ""
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.upper().startswith("TITLE:"):
            title = stripped.split(":", 1)[1].strip()
            break

    raw_blocks: list[tuple[str, list[str]]] = []
    current_headline: str | None = None
    buffer: list[str] = []

    def flush() -> None:
        if current_headline is not None:
            raw_blocks.append((current_headline, list(buffer)))

    for line in text.splitlines():
        match = re.match(r"^\s*(?:#{1,4}\s*)?(?:scene\s*)?(\d+)\s*[|:\.\-]\s*(.*)$", line, flags=re.IGNORECASE)
        # Only treat as a scene divider if it starts with # or "scene 1:" or "1|" or "1."
        if (
            re.match(r"^\s*#{1,4}\s*(\d+)", line)
            or re.match(r"^\s*scene\s*\d+\s*[|:\.\-]", line, flags=re.IGNORECASE)
            or re.match(r"^\s*\d+\s*[|]\s*", line)
        ):
            flush()
            buffer = []
            m = re.search(r"^\s*(?:#{1,4}\s*)?(?:scene\s*)?\d+\s*[|:\.\-]?\s*(.*)$", line, flags=re.IGNORECASE)
            current_headline = m.group(1).strip() if m else ""
            continue
        if current_headline is not None:
            buffer.append(line)
    flush()

    if not raw_blocks:
        # The model ignored the format. Fall back to splitting on blank lines so
        # a usable result still comes out of a sloppy response.
        paragraphs = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
        raw_blocks = [("", [p]) for p in paragraphs]

    blocks: list[tuple[str, str, str]] = []
    for raw_headline, lines in raw_blocks:
        headline = raw_headline
        visual_keywords = ""

        # 1. Check for inline VISUAL tag in headline e.g. "Headline | VISUAL: forest glowing lantern" or "Headline [VISUAL: ...]"
        if " | VISUAL:" in headline or " | visual:" in headline.lower():
            parts = re.split(r"\s*\|\s*visual:\s*", headline, flags=re.IGNORECASE, maxsplit=1)
            headline = parts[0].strip()
            visual_keywords = parts[1].strip() if len(parts) > 1 else ""
        elif "[VISUAL:" in headline or "[visual:" in headline.lower():
            v_match = re.search(r"\[visual:\s*([^\]]+)\]", headline, flags=re.IGNORECASE)
            if v_match:
                visual_keywords = v_match.group(1).strip()
                headline = re.sub(r"\[visual:\s*[^\]]+\]", "", headline, flags=re.IGNORECASE).strip()
        elif "(VISUAL:" in headline or "(visual:" in headline.lower():
            v_match = re.search(r"\(visual:\s*([^\)]+)\)", headline, flags=re.IGNORECASE)
            if v_match:
                visual_keywords = v_match.group(1).strip()
                headline = re.sub(r"\(visual:\s*[^\)]+\)", "", headline, flags=re.IGNORECASE).strip()

        # 2. Check if any line in the body contains a VISUAL tag and clean it from spoken body
        clean_lines = []
        for line in lines:
            stripped = line.strip()
            # If line starts with VISUAL: or [VISUAL: ...]
            if re.match(r"^\[?\s*visual\s*:\s*", stripped, flags=re.IGNORECASE):
                extracted = re.sub(r"^\[?\s*visual\s*:\s*", "", stripped, flags=re.IGNORECASE).rstrip("]").strip()
                if not visual_keywords:
                    visual_keywords = extracted
                continue
            # Remove any embedded [VISUAL: ...] tags inside prose so TTS won't read it aloud
            cleaned = re.sub(r"\[visual:\s*[^\]]+\]", "", line, flags=re.IGNORECASE)
            cleaned = re.sub(r"\(visual:\s*[^\)]+\)", "", cleaned, flags=re.IGNORECASE)
            clean_lines.append(cleaned)

        body = " ".join(" ".join(clean_lines).split())
        blocks.append((headline, visual_keywords, body))

    return title, blocks[:scene_count]


